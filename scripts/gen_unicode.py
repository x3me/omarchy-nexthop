import re
import sys
import unicodedata


def ranges(pred, lo=0):
    out, start = [], None
    for cp in range(lo, 0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    lines = ["pub static %s: &[(u32, u32)] = &[" % name]
    for i in range(0, len(rs), 6):
        lines.append("    " + " ".join("(0x%X, 0x%X)," % r for r in rs[i:i + 6]))
    lines.append("];")
    return "\n".join(lines)


unsafe = ranges(lambda cp: unicodedata.category(chr(cp)) in ("Cc", "Cf", "Cs", "Cn"))
word = ranges(lambda cp: re.match(r"\w", chr(cp)) is not None, 0x80)
print("// INFO: fc 17oct26 generated by scripts/gen_unicode.py from Python %s unicodedata (Unicode %s)"
      % (sys.version.split()[0], unicodedata.unidata_version))
print("#[rustfmt::skip]")
print(emit("UNSAFE_RANGES", unsafe))
print()
print("#[rustfmt::skip]")
print(emit("WORD_RANGES_NON_ASCII", word))
